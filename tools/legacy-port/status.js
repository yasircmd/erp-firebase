// Rewrites README.md's generated-port status block (between the
// PORT-STATUS markers) from modules.json + deployed.json + the screens.
//   node tools/legacy-port/status.js
const fs = require('fs'), path = require('path');
const REPO = path.resolve(__dirname, '../..');
const ORDER = ['UOM', 'ITEMSUBCAT', 'ORGUNITS', 'COMPANYMASTER', 'CURRENCYCONFIG', 'ITEMMASTER', 'COA', 'VENDORMASTER',
  'CUSTOMERMASTER', 'PRICELISTING', 'PROCUREMENTSETUP', 'SALESINVOICESETUP', 'ROLES', 'USERMGMT', 'TREEMGMT', 'APPROVALCONFIG',
  'APPROVALTRACKER', 'STOCKAVAILABILITY', 'STOCKLEDGER', 'STOCKVALUATION', 'INVENTORYVALUATION', 'MATERIALVARIANCE', 'GLREPORT',
  'TRIALBALANCE', 'BALANCESHEET', 'PROFITLOSS', 'CASHFLOW', 'PHYSICALCOUNT', 'BOM', 'JOBORDERREQUEST', 'PRODUCTION',
  'PRODCONSUMPTION', 'PURCHASEREQUISITION', 'INVENTORYPURCHASEREQUISITION', 'PURCHASEORDER', 'SALESORDER', 'DELIVERYNOTE',
  'JV', 'CBT', 'VENDORINVOICE', 'CUSTOMERINVOICE', 'DATARESET'];
const ported = require('./modules.json').modules;
const deployed = new Set(require('./deployed.json').deployedModules);
const callables = new Set([...fs.readFileSync(path.join(REPO, 'functions/src/legacy/callables.js'), 'utf8').matchAll(/^exports\.(\w+)/gm)].map(m => m[1]));
const fnsOf = mod => [...new Set([...fs.readFileSync(path.join(REPO, 'legacy-gas', mod + '.html'), 'utf8').matchAll(/['".](\w+)['"]?\(\s*(token|idToken)\b|['"](\w+)['"]/g)]
  .map(m => m[1] || m[3]).filter(f => callables.has(f)))];
const deployedFns = new Set([...deployed].flatMap(fnsOf));
const pendingMods = ported.filter(m => !deployed.has(m));
const pendingFns = [...new Set(pendingMods.flatMap(fnsOf))].filter(f => !deployedFns.has(f)).sort();
const next = ORDER.find(m => !ported.includes(m));
let block = '<!-- PORT-STATUS:start (generated by tools/legacy-port/status.js — do not edit by hand) -->\n';
block += '| Module | Ported (committed) | Deployed |\n|---|---|---|\n';
for (const m of ORDER) block += '| ' + m + ' | ' + (ported.includes(m) ? '✅' : '—') + ' | ' + (deployed.has(m) ? '✅' : (ported.includes(m) ? '**not yet**' : '—')) + ' |\n';
block += '\n**Next module to port:** ' + (next || '(none — all ported)') + '\n\n';
if (pendingFns.length) {
  block += '**Committed but NOT yet deployed** (' + pendingMods.join(', ') + ') — deploy these ' + (pendingFns.length + 1) +
    ' functions (≤6 per `firebase deploy --only functions:a,functions:b,...` batch), then add the public-invoker IAM binding to each, then add the modules to `tools/legacy-port/deployed.json` and rerun this script:\n\n```\ngetModuleFragment ' + pendingFns.join(' ') + '\n```\n';
} else block += 'Everything ported is deployed.\n';
block += '<!-- PORT-STATUS:end -->';
const readme = path.join(REPO, 'README.md'); let s = fs.readFileSync(readme, 'utf8');
const re = /<!-- PORT-STATUS:start[\s\S]*?<!-- PORT-STATUS:end -->/;
if (!re.test(s)) throw new Error('PORT-STATUS markers missing from README.md');
fs.writeFileSync(readme, s.replace(re, block));
console.log('README status updated: ' + ported.length + ' ported, ' + deployed.size + ' deployed, next ' + next + ', pending fns ' + pendingFns.length);
